#Requires -Version 5.1
<#
.SYNOPSIS
    MSIXForcelets fix for an MSIX package of LibreOffice 26.8.2.2 (LibreOffice_26.8.2_Win_x86-64.msi).
.DESCRIPTION
    Applied to the package captured with the MSIX Packaging Tool (package description: LibreOffice.psd1).
    The package runs installed (Add-AppxPackage) and from an App Attach CimFS image.

    Started from the script generated by Find-MSIXPackageIssue, which delegates to the MSIXForcelets known-application
    fix Add-MSIXFixLibreOffice (InstalledLocationVirtualization + SharedFonts + VisualGroup). This fix applies its
    parts individually WITHOUT InstalledLocationVirtualization: with ILV the package does not start from a CimFS
    App Attach image (0x801F000F), and no LibreOffice test needs ILV.
    Details and test results: README.md.
.PARAMETER MsixFile      Unfixed package.
.PARAMETER OutputFile    Fixed package (default: <MsixFile>_fixed.msix).
.PARAMETER PfxFile       Optional signing certificate.
.PARAMETER PfxPassword   Password of the PFX (SecureString).
#>
param(
    [Parameter(Mandatory = $true)] [string] $MsixFile,
    [string] $OutputFile = ($MsixFile -replace '\.msix$', '_fixed.msix'),
    [string] $PfxFile,
    [System.Security.SecureString] $PfxPassword
)
$ErrorActionPreference = 'Stop'
Import-Module MSIXForcelets

# Expand the package into a working folder.
$Package = Open-MSIXPackage -MsixFile $MsixFile -Force

# Problem: 127 fonts in VFS\Fonts (e.g. Liberation fonts for MS Office layout compatibility) are only visible to the
#   application without a SharedFonts declaration; part of Add-MSIXFixLibreOffice (known-app fix).
Add-MSIXSharedFonts -MSIXFolderPath $Package

# Problem: seven Start menu tiles without grouping; part of Add-MSIXFixLibreOffice: Start menu folder "LibreOffice"
#   (Windows 11). Cosmetic.
Set-MSIXApplicationVisualElements -MSIXFolderPath $Package -VisualGroup 'LibreOffice'

# Not applied: Add-MSIXInstalledLocationVirtualization (third part of Add-MSIXFixLibreOffice).
#   With ILV the package does not start from a CimFS App Attach image: AppModel-Runtime 216/208 0x801F000F
#   "Cannot create the Desktop AppX container". The same package without ILV starts.
#   LibreOffice writes its user profile and extensions to %APPDATA%, not to the install folder.

# Problem: desktop7 shortcuts in [{Common Programs}]\LibreOffice show no icon and can block the installation
#   (0x800700A1). The Start menu tiles of the applications remain.
Remove-MSIXDesktop7Shortcut -MSIXFolderPath $Package

# Problem: the package declares the service LibreOfficeMaintenance (update_service.exe, localSystem). A packaged
#   service needs administrative rights, so standard users cannot install the package; the update service cannot
#   update an MSIX package anyway. Removes the service, its host application LIBREOFFICEMAINTENANCE and the
#   capabilities packagedServices/localSystemServices.
#   Test: installation failed with 0x80073D28 "administrator rights required to install the package service".
Remove-MSIXServices -MSIXFolderPath $Package

# Problem: program\python.exe -> program\python-core-3.13.17\bin\python.exe imports python313.dll, which exists only in
#   program\. In the container the loader does not find it, Python hangs on the system error dialog and Python-UNO
#   (macros, scripting, Python extensions) does not work.
#   Test: python.exe -c "import uno" timed out, dialog "...python313.dll was not found"; ok with this line.
Add-MSIXloaderSearchPathOverride -MSIXFolderPath $Package -FolderPaths @('VFS\ProgramFilesX64\LibreOffice\program')

# Problem: the MSIX Packaging Tool took the display name of the application SOFFICE from the safe-mode shortcut
#   ("LibreOffice (Safe Mode)", --safe-mode); the application itself starts without parameters, so the Start menu
#   tile is misnamed.
Set-MSIXApplicationVisualElements -MSIXFolderPath $Package -Id 'SOFFICE' -DisplayName 'LibreOffice'

# Cleanup: the capture added a dependency on Microsoft.WindowsAppRuntime.1.4; LibreOffice does not use the Windows App
#   SDK (no WinAppSDK DLLs in the package, no reference in 163 program\*.exe/*.dll). Without removal the installation
#   fails with 0x80073CF3 where the runtime is missing.
#   Test: all tests ok on Windows Server 2025 without the runtime.
Remove-MSIXDependencies -MSIXFolderPath $Package -Name 'Microsoft.WindowsAppRuntime*'

# Pack the final package.
Close-MSIXPackage -MSIXFolder $Package -MSIXFile $OutputFile -Force

# Optional signing.
if ($PfxFile) {
    Set-MSIXSignature -MSIXFile $OutputFile -PfxCert $PfxFile -CertPassword $PfxPassword
}
