#Requires -Version 5.1
<#
.SYNOPSIS
    MSIXForcelets fix for an MSIX package of R 4.6.2 and RStudio 2026.11.0-203 (package name RuRStudio).
.DESCRIPTION
    Applied to the package captured with the MSIX Packaging Tool (package description: RuRStudio.psd1, installer
    wrapper: Install-RuRStudio.cmd). The package runs installed (Add-AppxPackage) and from an App Attach CimFS image.

    Started from the script generated by Find-MSIXPackageIssue, reduced to the changes that a test requires.
    Neither InstalledLocationVirtualization (breaks App Attach from CimFS) nor the PSF: the read-only R library is
    solved by R's own personal library (Rprofile.site.append.R in this folder).
    Why neither ILV nor PSF, and test results: README.md. A corrected PSF MFRFixup (DLL and source):
    CustomMFRFixup\.
.PARAMETER MsixFile      Unfixed package.
.PARAMETER OutputFile    Fixed package (default: <MsixFile>_fixed.msix).
.PARAMETER PfxFile       Optional signing certificate.
.PARAMETER PfxPassword   Password of the PFX (SecureString).
#>
param(
    [Parameter(Mandatory = $true)] [string] $MsixFile,
    [string] $OutputFile = ($MsixFile -replace '\.msix$', '_fixed.msix'),
    [string] $PfxFile,
    [System.Security.SecureString] $PfxPassword
)
$ErrorActionPreference = 'Stop'
Import-Module MSIXForcelets
$FixFiles = $PSScriptRoot

# Expand the package into a working folder.
$Package = Open-MSIXPackage -MsixFile $MsixFile -Force

# Problem: the installer leaves R 4.6.2.lnk in VFS\Common Desktop; MSIX never shows files there on the desktop.
Remove-Item -LiteralPath (Join-Path $Package 'VFS\Common Desktop\R 4.6.2.lnk') -Force

# Problem: the R library (VFS\ProgramFilesX64\R\R-4.6.2\library) is read-only in the container, so
#   install.packages() fails ("'lib = ...' is not writable").
#   Not usable (details README.md):
#   - InstalledLocationVirtualization: the package does not start from a CimFS App Attach image (0x801F000F).
#   - PSF MFRFixup and FileRedirectionFixup (release 2026-11-14): install.packages() fails and RStudio shows errors.
#   Measure: append a block to R's site profile R_HOME\etc\Rprofile.site that creates R's default personal library
#   R_LIBS_USER (%LOCALAPPDATA%\R\win-library\4.6) and puts it first in .libPaths(); every R process of the package
#   reads this file. No Forcelets cmdlet adds content without PSF (Copy-ToMSIXPackage needs config.json.xml),
#   therefore a file operation in the expanded package, like the Remove-Item above.
#   Test: install.packages("jsonlite") and library(jsonlite) in a new process, installed and as CIM.
$rprofile = Join-Path $Package 'VFS\ProgramFilesX64\R\R-4.6.2\etc\Rprofile.site'
if (-not (Test-Path -LiteralPath $rprofile)) { throw "Rprofile.site not found in the package: $rprofile" }
if (-not (Select-String -LiteralPath $rprofile -SimpleMatch 'MSIX package RuRStudio' -Quiet)) {
    Add-Content -LiteralPath $rprofile -Value (Get-Content -LiteralPath (Join-Path $FixFiles 'Rprofile.site.append.R') -Raw) -Encoding ASCII
}

# Problem: rstudio.exe cannot be started by name (Win+R, other programs); App Paths entries in the package
#   registry are not visible outside the container.
Add-MSIXAppExecutionAlias -MSIXFolder $Package -MSIXAppID 'RSTUDIO' -CommandlineAlias 'rstudio.exe' -Executable 'VFS\ProgramFilesX64\RStudio\rstudio.exe'

# Problem: the R session (rsession-utf8.exe -> rsession.dll) needs R.dll and Rgraphapp.dll from R\R-4.6.2\bin\x64;
#   RStudio passes R_HOME as an 8.3 short path that does not resolve in the container, so the loader does not find
#   R.dll and rsession exits with 0xC0000135 STATUS_DLL_NOT_FOUND.
#   Test: RStudio "Error Starting R" (rdesktop.log: "rsession exited: code=3221225781"); ok with this line.
Add-MSIXloaderSearchPathOverride -MSIXFolderPath $Package -FolderPaths @('VFS\ProgramFilesX64\R\R-4.6.2\bin\x64')

# Cleanup 1: the MSIX Packaging Tool added a dependency on Microsoft.WindowsAppRuntime.1.4 during capture.
#   Neither R nor RStudio uses the Windows App SDK (no WinAppSDK DLLs in the package, no reference in 37 R/RStudio
#   binaries). Without removal Add-AppxPackage fails with 0x80073CF3 where the framework is missing.
Remove-MSIXDependencies -MSIXFolderPath $Package -Name 'Microsoft.WindowsAppRuntime*'

# Cleanup 2: remove all desktop7:Shortcut entries and their .lnk ([{Common Programs}]\RStudio.lnk,
#   [{Common Programs}]\R\R 4.6.2.lnk, [{Desktop}]\R 4.6.2.lnk). Shortcuts in system locations show no icon and can
#   block the installation (0x800700A1); the Start menu tiles of RSTUDIO and RGUI remain.
Remove-MSIXDesktop7Shortcut -MSIXFolderPath $Package

# Pack the folder into the output package.
Close-MSIXPackage -MSIXFolder $Package -MSIXFile $OutputFile -Force

# Optional signing.
if ($PfxFile) {
    Set-MSIXSignature -MSIXFile $OutputFile -PfxCert $PfxFile -CertPassword $PfxPassword
}
